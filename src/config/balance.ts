// ─── Предметы врагов ─────────────────────────────────────────────────────────
// Как враг пользуется сумкой (режим предмета задан в src/data/enemyItems.ts):
//  • «действие» — враг делает одно действие за раз. Следующее действие — первый ДОСТУПНЫЙ предмет
//    сумки по priority (есть заряды, выполнено условие). Таймер врага копится до cooldown
//    этого предмета, предмет срабатывает, таймер обнуляется. Так снаряды с зарядами идут первыми,
//    а основное оружие — когда заряды кончились.
//  • «пассивный» — срабатывает сам по своей перезарядке, параллельно действиям (щит).
//  • «при ударе» — срабатывает каждый раз, когда действие врага наносит урон герою (мешок).
// Урон, лечение и блок умножаются на ENEMY_STAT_MULT_BY_NIGHT.

export interface EnemyItemStats {
  /** Секунд до срабатывания (для действий — время подготовки, для пассивных — перезарядка). */
  cooldown?: number;
  /** Зарядов у ОДНОГО предмета на бой с этим врагом; кончились — предмет исчезает из сумки. Нет поля — без ограничений. */
  charges?: number;
  /** Урон герою. */
  damage?: number;
  /** Множитель урона по герою-монстру (Людьмак всегда монстр). */
  monsterMult?: number;
  /** Блок врагу (копится до ENEMY_BLOCK_MAX). */
  block?: number;
  /** Лечение врага. */
  heal?: number;
  /** Условие: предмет доступен, только когда здоровье врага ниже этой доли (0..1). */
  healBelow?: number;
  /** Сколько монет крадёт из награды текущего заказа за удар. */
  stealCoins?: number;
}

