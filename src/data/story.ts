/** Напоминание в шапке: сколько ночей до прихода ведьмака (0 — сегодня). */
export function witcherReminder(nightsLeft: number): string {
  if (nightsLeft <= 0) return 'Ведьмак придёт сегодня';
  if (nightsLeft === 1) return 'Ведьмак придёт через 1 ночь';
  return `Ведьмак придёт через ${nightsLeft} ${nightsLeft < 5 ? 'ночи' : 'ночей'}`;
}
